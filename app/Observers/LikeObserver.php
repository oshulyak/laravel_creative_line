<?php

namespace App\Observers;

use App\Models\Comment;
use App\Models\Like;
use App\Models\Post;

class LikeObserver {
    /**
     * Лайк поставлен — уведомляем автора записи.
     *
     * Обсервер срабатывает только потому, что в связях лайков стоит
     * ->using(Like::class): без него attach() пишет строку прямым запросом,
     * модель не создаётся и событий нет.
     */
    public function created(Like $like): void {
        $target = $like->likeable;

        // Лайкать можно ещё и изображения, но у Image нет автора-профиля,
        // и уведомлять некого. Проверка по типам заодно объясняет, почему
        // ниже можно спокойно брать author_id: он есть и у поста, и у комментария.
        if (! $target instanceof Post && ! $target instanceof Comment) {
            return;
        }

        // ВРЕМЕННО ОТКЛЮЧЕНО: чтобы уведомления было видно, лайкая собственные
        // записи одним аккаунтом. Вернуть после проверки интерфейса.
        //
        // Лайк собственной записи уведомления не порождает.
        // if ($target->author_id === $like->profile_id) {
        //     return;
        // }

        $body = $target instanceof Post
            ? 'Новый лайк публикации «'.$target->title.'»'
            : 'Новый лайк вашего комментария';

        // firstOrCreate, а не create: лайк можно снять и поставить заново сколько
        // угодно раз, и каждый повтор — это событие created.
        //
        // Первый массив — условия поиска, второй — то, что запишется, если строки
        // нет. Ищем по тройке «кому + от кого + ещё не прочитано»; связь сама
        // добавит в условие notificationable_type и notificationable_id, то есть
        // конкретную запись. Как только пользователь увидел уведомление, read_at
        // заполнился — и следующий лайк того же человека создаст новую строку.
        // Это верно: событие действительно новое.
        //
        // Источником пишем сам пост или комментарий, а не лайк: лайк снимут,
        // строка в likeables исчезнет, и уведомление осталось бы со ссылкой
        // в никуда. Пост же никуда не денется.
        $target->notifications()->firstOrCreate(
            [
                'profile_id' => $target->author_id,
                'actor_id' => $like->profile_id,
                'read_at' => null,
            ],
            [
                'body' => $body,
            ],
        );
    }
}
