<?php

namespace App\Observers;

use App\Models\Notification;

/**
 * УЧЕБНЫЙ ЭКСПЕРИМЕНТ, а не образец для продакшена.
 *
 * Обсервер превращает любое ЧТЕНИЕ уведомления в запись: не только показ
 * в попапе, но и консольную команду, отчёт, отладочный Notification::find()
 * в tinker. Заодно GET-запрос списка начинает менять состояние, хотя по
 * семантике HTTP обязан быть безопасным.
 *
 * Так сделано потому, что этого требует домашнее задание 30-го урока
 * («реализовать обновление read_at в обсервере») и потому что это наглядно
 * показывает цену «невидимых» побочных эффектов. Нормальное решение —
 * отдельный маршрут PATCH «пометить показанные прочитанными» и один UPDATE.
 */
class NotificationObserver {
    /**
     * Уведомление достали из базы — значит его показали, значит оно прочитано.
     */
    public function retrieved(Notification $notification): void {
        if ($notification->read_at !== null) {
            return;
        }

        // Запоминаем, что в момент показа уведомление было новым: ресурс уже
        // не смог бы это определить — read_at заполнится строкой ниже.
        $notification->wasUnread = true;

        $notification->read_at = now();

        // saveQuietly(), а не save(): обычное сохранение подняло бы события
        // saving, saved, updating, updated. Тишина и ради лишней работы,
        // и ради страховки от рекурсии, если в этом обсервере однажды появится
        // метод updated(), который снова читает модель.
        $notification->saveQuietly();
    }
}
